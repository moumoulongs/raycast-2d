WorldMap::WorldMap()
    : width_(kMapWidth),
      height_(kMapHeight),
      tiles_(kDefaultTiles.begin(), kDefaultTiles.end()) {}

int WorldMap::width() const {
    return width_;
}

int WorldMap::height() const {
    return height_;
}

bool WorldMap::contains(int x, int y) const {
    return x >= 0 && y >= 0 && x < width_ && y < height_;
}

int WorldMap::tileAt(int x, int y) const {
    if (!contains(x, y)) {
        return 1;
    }
    return tiles_[static_cast<std::size_t>(y * width_ + x)];
}

bool WorldMap::isWall(int x, int y) const {
    return tileAt(x, y) > 0;
}
